test('ativação é explícita e preserva o histórico completo em backup exportável',async({page})=>{
  const legacy=seed();
  delete legacy.plan.curriculumId;delete legacy.archives;
  legacy.plan.name='Plano anterior de 160h';legacy.plan.weeklyHours=10;
  legacy.weeks.forEach(week=>{week.plannedHours=10;week.phase='Fundamentos';});
  legacy.weeks[0].title='Fundamentos de qualidade';legacy.weeks[0].notes='Minha nota preservada';
  legacy.weeks[0].status='Concluída';
  legacy.sessions=[{id:'legacy-session',title:'Estudo anterior',weekId:'1',status:'Registrada',date:'2026-10-29',durationMinutes:'120'}];
  await page.goto('/');
  await page.evaluate(data=>localStorage.setItem('qa-path-v1',JSON.stringify(data)),legacy);
  await page.reload();
  await expect(page.getByText('160h planejadas · 16 semanas')).toBeVisible();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'Ativar roteiro de 96h'}).click();
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('qa-path-v1')!).plan.name)).toBe('Plano anterior de 160h');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Ativar roteiro de 96h'}).click();
  await expect(page.getByRole('heading',{name:'Meu plano',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('96h planejadas · 16 semanas')).toBeVisible();
  await expect(page.getByRole('button',{name:'Ativar roteiro de 96h'})).toHaveCount(0);
  await page.getByRole('button',{name:'Configurações',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Planos anteriores preservados'})).toBeVisible();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar plano',exact:true}).click();
  const download=await downloadPromise;
  const archived=JSON.parse(await fs.readFile((await download.path())!,'utf8'));
  expect(archived).toEqual(legacy);
  expect(archived.weeks[0].notes).toBe('Minha nota preservada');
  expect(archived.sessions[0].durationMinutes).toBe('120');
});

test('configurações mantêm a identidade da trilha e navegação funciona por teclado',async({page})=>{
  await page.goto('/');
  const planButton=page.getByRole('button',{name:'Meu plano',exact:true});
  await planButton.focus();await page.keyboard.press('Enter');
  await expect(page.getByRole('heading',{name:'Meu plano',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Configurações',exact:true}).click();
  await page.getByLabel('Nome do plano').fill('Meu foco QA');
  await page.getByRole('button',{name:'Salvar configurações'}).click();
  await page.reload();
  await expect(page.getByRole('button',{name:'Ativar roteiro de 96h'})).toHaveCount(0);
  await page.getByRole('button',{name:'Configurações',exact:true}).click();
  await expect(page.getByLabel('Nome do plano')).toHaveValue('Meu foco QA');
  await expect(page.getByLabel('Horas planejadas por semana')).toHaveValue('6');
});
